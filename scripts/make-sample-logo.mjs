// Generates src/lib/samples/logo-png.ts: a small procedural logo for the Invoice sample (design D10).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encodePng } from './png.mjs';

const S = 64;
const png = encodePng(S, S, (x, y) => {
  const dx = x - S / 2 + 0.5;
  const dy = y - S / 2 + 0.5;
  const r = Math.hypot(dx, dy);
  if (r > 30) return [0, 0, 0, 0];
  if (r > 26) return [30, 41, 59, 255]; // ring
  if (Math.abs(dx + dy) < 5) return [255, 255, 255, 255]; // diagonal stripe
  return [37, 99, 235, 255];
});
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'samples', 'logo-png.ts');
writeFileSync(
  target,
  `// Generated by scripts/make-sample-logo.mjs. Do not edit.\n` +
    `export const LOGO_PNG_BASE64 =\n  '${png.toString('base64')}';\n`,
);
console.log(`${target} (${png.length} bytes)`);
